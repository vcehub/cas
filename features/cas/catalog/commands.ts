/** Sorted as the handheld sorts: by letters, ignoring case and the ▶ and Δ prefixes; symbols last. */
const key = (n: string) => {
  const k = n.replace(/^[▶Δ]/, "").toLowerCase();
  return /^[a-z]/.test(k) ? k : `~${k}`;
};
const SORTED: CatalogEntry[] = [...LIST].sort((p, q) => key(p.name).localeCompare(key(q.name), "en"));

/** What the catalog shows. */
export const CATALOG: CatalogEntry[] = SORTED.filter((e) => e.syntax);

/** Every command name the parser should recognise, shown or not. */
export const COMMAND_NAMES: string[] = SORTED.map((e) => e.name);

export const catalogInsert = (e: CatalogEntry) => e.insert ?? e.name;
